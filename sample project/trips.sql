DROP SCHEMA IF EXISTS trips CASCADE;
CREATE SCHEMA IF NOT EXISTS trips;

CREATE TABLE trips.members (
    member_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(50) NOT NULL,
    last_name varchar(50) NOT NULL,
    registered_at timestamptz NOT NULL DEFAULT now(),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE trips.trips (
    trip_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    starts_on date NOT NULL,
    ends_on date NOT NULL,
    expected_cost numeric(10, 2),
    CONSTRAINT trips_dates_valid CHECK (ends_on >= starts_on),
    CONSTRAINT trips_expected_cost_nonnegative CHECK (
        expected_cost IS NULL OR expected_cost >= 0
    )
);

CREATE TABLE trips.participants (
    participant_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id integer NOT NULL REFERENCES trips.members (member_id),
    trip_id integer NOT NULL REFERENCES trips.trips (trip_id),
    is_active boolean NOT NULL DEFAULT true,
    is_leader boolean NOT NULL DEFAULT false,
    CONSTRAINT participants_member_trip_unique UNIQUE (member_id, trip_id)
);

CREATE TABLE trips.services (
    service_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(90) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE trips.expenses (
    expense_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id integer NOT NULL REFERENCES trips.services (service_id),
    trip_id integer NOT NULL REFERENCES trips.trips (trip_id),
    amount numeric(10, 2) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    description text,
    CONSTRAINT expenses_amount_positive CHECK (amount > 0)
);

CREATE TABLE trips.expense_shares (
    expense_share_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id integer NOT NULL REFERENCES trips.participants (participant_id),
    expense_id integer NOT NULL REFERENCES trips.expenses (expense_id),
    share_amount numeric(10, 2) NOT NULL,
    description text,
    CONSTRAINT expense_shares_amount_nonnegative CHECK (share_amount >= 0),
    CONSTRAINT expense_shares_participant_expense_unique
        UNIQUE (participant_id, expense_id)
);

CREATE TABLE trips.payments (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id integer NOT NULL REFERENCES trips.participants (participant_id),
    is_confirmed boolean NOT NULL DEFAULT false,
    amount numeric(10, 2) NOT NULL,
    paid_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT payments_amount_positive CHECK (amount > 0)
);

-- Indexy na cizí klíče, přes které vyúčtování vyhledává data výletu.
CREATE INDEX participants_trip_id_idx ON trips.participants (trip_id);
CREATE INDEX expenses_trip_id_idx ON trips.expenses (trip_id);
CREATE INDEX expense_shares_expense_id_idx ON trips.expense_shares (expense_id);
CREATE INDEX payments_participant_id_idx ON trips.payments (participant_id);

